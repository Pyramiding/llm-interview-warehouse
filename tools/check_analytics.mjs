import assert from 'node:assert/strict';
import {privacyDisabled,isProductionLocation,visitPayload,validatedStats,recordVisit,readStats} from '../site/analytics.mjs';
const config={siteOrigin:'https://pyramiding.github.io',sitePath:'/llm-interview-warehouse/'};
assert.equal(privacyDisabled({doNotTrack:'1'}),true);
assert.equal(privacyDisabled({globalPrivacyControl:true}),true);
assert.equal(privacyDisabled({},true),true);
assert.equal(privacyDisabled({}),false);
assert.equal(isProductionLocation({origin:'http://localhost:8876',pathname:'/'},config),false);
assert.equal(isProductionLocation({origin:'https://pyramiding.github.io',pathname:'/another-project/'},config),false);
assert.equal(isProductionLocation({origin:config.siteOrigin,pathname:config.sitePath},config),true);
assert.deepEqual(visitPayload('invalid','event','token'),{eventId:'event',token:'token',view:'interviews'});
for(const invalid of [{total:-1,today:0,todayIps:0},{total:'5',today:0,todayIps:0},{total:5,today:Infinity,todayIps:0}])assert.throws(()=>validatedStats(invalid));
const stats={total:7,today:4,todayIps:2};const calls=[];
const fake=async(url,options)=>{calls.push({url,options});return new Response(JSON.stringify(url.endsWith('/challenge')?{token:'test-nonce'}:{stats}),{status:200,headers:{'content-type':'application/json'}})};
assert.deepEqual(await recordVisit('https://analytics.example.test','questions',{fetcher:fake,eventId:'test-event'}),stats);
assert.equal(calls.length,2);
assert.equal(calls[0].options.credentials,'omit');
assert.equal(calls[1].options.referrerPolicy,'origin');
const body=JSON.parse(calls[1].options.body);
assert.deepEqual(body,{eventId:'test-event',token:'test-nonce',view:'questions'});
for(const key of ['ip','email','search','query','referrer','url','userAgent'])assert(!Object.hasOwn(body,key));
assert.equal(calls[1].options.headers.Authorization,undefined);
let sent=0;
await assert.rejects(()=>recordVisit('https://analytics.example.test','interviews',{fetcher:async()=>{sent++;return new Response('',{status:503})},eventId:'test-event'}));
assert.equal(sent,1);
const abortController=new AbortController();abortController.abort();
await assert.rejects(()=>recordVisit('https://analytics.example.test','interviews',{eventId:'test-event',signal:abortController.signal,fetcher:async(_url,options)=>{options.signal.throwIfAborted();throw new Error('should be aborted')}}));
let readOptions;
assert.deepEqual(await readStats('https://analytics.example.test',async(_url,options)=>{readOptions=options;return new Response(JSON.stringify(stats),{status:200})}),stats);
assert.equal(readOptions.credentials,'omit');
assert.equal(readOptions.method,undefined);
console.log('Analytics client checks passed: privacy controls, production-only tracking, bounded payloads, failures and cancellation.');
